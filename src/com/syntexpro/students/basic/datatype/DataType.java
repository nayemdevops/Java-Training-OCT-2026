package com.syntexpro.students.basic.datatype;

public class DataType {

    public static void main(String[] args) {


        byte Nayem = 99;
        System.out.println(Nayem);

        long Irfan = 90L;
        System.out.println(Irfan);

        float Ferdous = 89.123456789F;
        System.out.println(Ferdous);

        double Tareq = 69.1234567890123456;
        System.out.println(Tareq);

        char Nahid = '5';
        System.out.println(Nahid);

        boolean wust = true;
        System.out.println(wust);




    }


}
